export function t(lang: LanguageCode, key: string): string {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
}

export function localizedCategoryName(
  cat: { nameEn?: string; nameSo?: string; nameAr?: string } | null | undefined,
  lang: LanguageCode
): string {
  if (!cat) return '';
  if (lang === 'so') return cat.nameSo || cat.nameEn || '';
  if (lang === 'ar') return cat.nameAr || cat.nameEn || '';
  return cat.nameEn || '';
}

export function localizedSectionTitle(
  sec: { titleEn?: string; titleSo?: string; titleAr?: string } | null | undefined,
  lang: LanguageCode
): string {
  if (!sec) return '';
  if (lang === 'so') return sec.titleSo || sec.titleEn || '';
  if (lang === 'ar') return sec.titleAr || sec.titleEn || '';
  return sec.titleEn || '';
}
